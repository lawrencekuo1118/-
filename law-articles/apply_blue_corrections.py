BLUE = Font(name="微軟正黑體", color="0000FF", size=11)
BLUE_BOLD = Font(name="微軟正黑體", color="0000FF", size=11, bold=True)

changelog: list[tuple[str, int | str, str, str]] = []


def blue_set(ws, row: int, col: int, value, bold: bool = False):
    cell = ws.cell(row=row, column=col, value=value)
    cell.font = BLUE_BOLD if bold else BLUE
    cell.alignment = Alignment(wrap_text=True, vertical="top")
    return cell


def blue_append(ws, row: int, col: int, suffix: str):
    cell = ws.cell(row=row, column=col)
    old = cell.value
    cell.value = ("" if old is None else str(old).rstrip("\n") + "\n") + suffix
    cell.font = BLUE
    cell.alignment = Alignment(wrap_text=True, vertical="top")
    return cell


def log(sheet, row, field, summary):
    changelog.append((sheet, row, field, summary))


